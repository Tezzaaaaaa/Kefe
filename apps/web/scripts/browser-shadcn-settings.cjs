const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '../dist-beui');
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png', '.woff2': 'font/woff2', '.webmanifest': 'application/manifest+json' };
const server = http.createServer((req, res) => {
  const file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404).end(); return; }
  res.writeHead(200, { 'content-type': mime[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
(async () => {
  let browser;
  try {
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.CHROMIUM_EXECUTABLE_PATH } : {}) });
    for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }]) {
      const context = await browser.newContext({ viewport, serviceWorkers: 'block' });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(`http://127.0.0.1:${server.address().port}/editor.html`);
      const opener = page.locator('[data-top-panel="settings"]');
      await opener.click();
      const dialog = page.getByRole('dialog', { name: 'Settings' });
      await dialog.waitFor({ state: 'visible' });
      const rect = await dialog.boundingBox();
      assert.ok(rect && rect.x >= 0 && rect.x + rect.width <= viewport.width, 'dialog fits the viewport');
      const accordion = dialog.locator('[data-slot="accordion-trigger"]');
      assert.equal(await accordion.count(), 3);
      const sw = dialog.getByRole('switch', { name: 'Show title card' });
      await sw.click();
      assert.equal(await page.evaluate(() => window.kefeSettings.get('titleCard')), false);
      await accordion.filter({ hasText: 'Engine' }).click();
      const slider = dialog.getByRole('slider', { name: 'FPS target' });
      await slider.focus(); await slider.press('ArrowRight');
      assert.equal(await page.evaluate(() => window.kefeSettings.get('fpsTarget')), 70);
      await accordion.filter({ hasText: 'Defaults' }).click();
      const select = dialog.getByRole('combobox', { name: 'Aspect ratio' });
      await select.click();
      const option = dialog.getByRole('option', { name: '9:16' });
      await option.click();
      assert.equal(await page.evaluate(() => window.kefeSettings.get('aspect')), '9:16');
      await dialog.getByRole('button', { name: 'Reset all settings' }).click();
      assert.deepEqual(await page.evaluate(() => [window.kefeSettings.get('titleCard'), window.kefeSettings.get('fpsTarget'), window.kefeSettings.get('aspect')]), [true, 60, '16:9']);
      await dialog.getByRole('button', { name: 'Done' }).click();
      await dialog.waitFor({ state: 'hidden' });
      await page.waitForFunction(() => document.activeElement?.matches('[data-top-panel="settings"]'));
      await opener.click(); await dialog.waitFor({ state: 'visible' });
      await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
      await page.waitForFunction(() => document.activeElement?.matches('[data-top-panel="settings"]'));
      await page.locator('[data-workspace-tab="export"]').evaluate(node => node.click());
      await page.locator('#kefe-subtab-export').evaluate(node => node.click());
      const format = page.locator('#exportFormat + [data-slot="select-trigger"]');
      await format.click();
      await page.getByRole('option', { name: 'MP4 (H.264/AAC where supported)' }).click();
      assert.equal(await page.locator('#exportFormat').inputValue(), 'mp4');
      await page.evaluate(() => { document.getElementById('exportFormat').value = 'webm'; });
      await page.waitForFunction(() => document.querySelector('#exportFormat + [data-slot="select-trigger"]')?.textContent.includes('WebM'));
      await page.evaluate(() => { document.getElementById('exportFormat').hidden = true; });
      await page.waitForFunction(() => document.getElementById('exportFormat').parentElement.hidden);
      assert.equal(await format.isVisible(), false, 'hidden backing select hides its shadcn control');
      await page.evaluate(() => { document.getElementById('exportFormat').hidden = false; });
      await page.waitForFunction(() => !document.getElementById('exportFormat').parentElement.hidden);
      const review = page.locator('#kefeReview0');
      const checkbox = page.getByRole('checkbox', { name: 'Read the lyrics silently: spelling, punctuation, line breaks.' });
      await checkbox.click();
      assert.equal(await review.isChecked(), true);
      await checkbox.focus();
      await page.keyboard.press('Space');
      assert.equal(await review.isChecked(), false);
      await page.locator('.kefe-review-item').first().click({ position: { x: 80, y: 8 } });
      assert.equal(await review.isChecked(), true, 'clicking the label should update the original input');
      await page.evaluate(() => { document.getElementById('kefeReview0').checked = false; });
      await page.waitForFunction(() => document.querySelector('#kefeReview0 + .kefe-checkbox-host [role="checkbox"]')?.getAttribute('aria-checked') === 'false');
      await page.evaluate(() => { document.getElementById('kefeReview0').hidden = true; });
      await page.waitForFunction(() => document.querySelector('#kefeReview0 + .kefe-checkbox-host').hidden);
      assert.equal(await checkbox.isVisible(), false, 'hidden backing input hides its shadcn control');
      await page.evaluate(() => { document.getElementById('kefeReview0').hidden = false; });
      await page.locator('[data-workspace-tab="content"]').evaluate(node => node.click());
      await page.locator('#kefe-subtab-lyric-sync').evaluate(node => node.click());
      const syncMoreTrigger = page.locator('#kefeAutoSync [data-slot="collapsible-trigger"]');
      if (await syncMoreTrigger.count()) {
        if (await syncMoreTrigger.getAttribute('aria-expanded') !== 'true') await syncMoreTrigger.click();
      } else {
        await page.locator('#kefeAutoSync details').evaluate(node => { node.open = true; });
      }
      await page.getByRole('combobox', { name: 'Speech recognition model' }).click();
      await page.getByRole('option', { name: 'English · Balanced' }).click();
      assert.equal(await page.locator('select[aria-label="Speech recognition model"]').inputValue(), 'base.en');
      await page.locator('[data-workspace-tab="design"]').evaluate(node => node.click());
      await page.locator('#kefe-subtab-lyric-effects').evaluate(node => node.click());
      await page.locator('#lyricEffectOptions [data-effect="textswap"]').evaluate(node => node.click());
      await page.getByRole('combobox', { name: 'Text Swap transition' }).click();
      await page.getByRole('option', { name: 'Crossfade' }).click();
      assert.equal(await page.evaluate(() => window.kefeTextSwapPreset), 'crossfade');
      const lyricsBacking = page.locator('#lyricsEnabledToggle');
      const lyricsSwitch = page.locator('#lyricsEnabledToggle + .kefe-switch-host [role="switch"]');
      const lyricsBefore = await lyricsBacking.getAttribute('aria-checked');
      await lyricsSwitch.click();
      assert.notEqual(await lyricsBacking.getAttribute('aria-checked'), lyricsBefore);
      await lyricsSwitch.focus(); await page.keyboard.press('Space');
      assert.equal(await lyricsBacking.getAttribute('aria-checked'), lyricsBefore);
      await page.evaluate(() => { document.getElementById('lyricsEnabledToggle').hidden = true; });
      await page.waitForFunction(() => document.querySelector('#lyricsEnabledToggle + .kefe-switch-host').hidden);
      assert.equal(await lyricsSwitch.isVisible(), false, 'hidden backing switch hides its shadcn control');
      await page.evaluate(() => { document.getElementById('lyricsEnabledToggle').hidden = false; });
      await page.locator('#kefe-subtab-background').evaluate(node => node.click());
      const bgBacking = page.locator('#kefeBackgroundEffectToggle');
      const bgSwitch = page.locator('#kefeBackgroundEffectToggle + .kefe-switch-host [role="switch"]');
      const bgBefore = await bgBacking.getAttribute('aria-checked');
      await bgSwitch.click();
      assert.notEqual(await bgBacking.getAttribute('aria-checked'), bgBefore);
      await page.evaluate(() => window.kefeProjectAutosave.setToolbarContext('background'));
      const contextTrigger = page.locator('#kefeFloatingToolbar button[aria-label="Lyric effect and text style"]');
      await contextTrigger.click();
      const toolbarContext = page.locator('.kft-context-popover');
      const contextSwitch = toolbarContext.locator('[role="switch"]:not([aria-hidden="true"])');
      assert.equal(await contextSwitch.count(), 1, 'toolbar must expose one background switch');
      const contextBefore = await bgBacking.getAttribute('aria-checked');
      await contextSwitch.click();
      assert.notEqual(await bgBacking.getAttribute('aria-checked'), contextBefore, 'toolbar switch toggles its backing control once');
      const darkness = toolbarContext.getByRole('slider', { name: /Background darkness/ });
      await darkness.waitFor({ state: 'visible' });
      await darkness.focus(); await page.keyboard.press('ArrowRight');
      await page.waitForTimeout(200); await page.keyboard.press('ArrowRight');
      assert.equal(await page.locator('#backgroundTransparency').inputValue(), '2', 'toolbar slider keeps focus and updates its source');
      await contextTrigger.click();
      await page.locator('[data-workspace-tab="audio-visuals"]').evaluate(node => node.click());
      await page.locator('#kefe-subtab-visualisers').evaluate(node => node.click());
      const cards = page.locator('.kv-card');
      assert.equal(await cards.count(), 7);
      for (let index = 0; index < await cards.count(); index++) {
        const card = cards.nth(index);
        const value = await card.getAttribute('data-visualiser');
        const backing = page.locator(`.shad-vis-backing-controls [data-visualiser="${value}"]`).locator('xpath=..').locator('.kefe-switch');
        const power = card.locator('[data-slot="switch"]');
        const before = await backing.getAttribute('aria-checked');
        await power.click();
        assert.notEqual(await backing.getAttribute('aria-checked'), before);
        await power.click();
        assert.equal(await backing.getAttribute('aria-checked'), before);
      }
      assert.deepEqual(errors, [], `page errors at ${viewport.width}px`);
      const savedBackground = await bgBacking.getAttribute('aria-checked');
      await page.evaluate(() => window.kefeProjectAutosave.saveNow());
      await page.reload({ waitUntil: 'networkidle' });
      await page.evaluate(() => window.kefeProjectAutosave.ready);
      await page.locator('[data-workspace-tab="design"]').evaluate(node => node.click());
      await page.locator('#kefe-subtab-background').evaluate(node => node.click());
      await page.waitForFunction(expected => document.querySelector('#kefeBackgroundEffectToggle + .kefe-switch-host [role="switch"]')?.getAttribute('aria-checked') === expected, savedBackground);
      assert.equal(await page.locator('#backgroundTransparency').inputValue(), '2', 'toolbar edit persists after reload');
      await context.close();
    }
    console.log('PASS: settings, editor select, checkbox and switch shadcn components in desktop and mobile Chromium');
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
