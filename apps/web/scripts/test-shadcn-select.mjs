import assert from "node:assert/strict";
import { JSDOM } from "jsdom";
import { createServer } from "vite";
const dom = new JSDOM('<!doctype html><html><body><section class="kefe-panel"><label for="fontOverride">Font</label><select id="fontOverride"><option value="">Effect font</option><option value="serif">Serif</option><option value="disabled" disabled>Disabled</option></select></section></body></html>', { url: "http://localhost/", pretendToBeVisual: true });
for (const key of ["window", "document", "HTMLElement", "HTMLInputElement", "HTMLSelectElement", "Element", "Node", "NodeFilter", "DocumentFragment", "MutationObserver", "Event", "KeyboardEvent", "CustomEvent", "getComputedStyle", "navigator"]) {
  Object.defineProperty(globalThis, key, { configurable: true, value: dom.window[key] });
}
globalThis.requestAnimationFrame = dom.window.requestAnimationFrame.bind(dom.window);
globalThis.cancelAnimationFrame = dom.window.cancelAnimationFrame.bind(dom.window);
globalThis.ResizeObserver = class { observe() {} unobserve() {} disconnect() {} };
dom.window.HTMLElement.prototype.scrollIntoView = function () {};
const server = await createServer({ configFile: false, server: { middlewareMode: true }, appType: "custom" });
const tick = () => new Promise(resolve => setTimeout(resolve, 60));
try {
  await server.ssrLoadModule("/beui-src/shadcn-select-bridge.js");
  if (document.readyState === "loading") document.dispatchEvent(new Event("DOMContentLoaded"));
  await tick();
  const native = document.getElementById("fontOverride");
  const trigger = native.nextElementSibling;
  assert.equal(trigger.getAttribute("data-slot"), "select-trigger");
  assert.equal(trigger.getAttribute("aria-label"), "Font");
  assert.match(trigger.textContent, /Effect font/);
  native.focus();
  assert.equal(document.activeElement, trigger, "label or programmatic focus reaches the visible trigger");
  Object.getOwnPropertyDescriptor(native, "value").set.call(native, "serif"); await tick();
  assert.match(trigger.textContent, /Serif/);
  native.options[1].textContent = "New Serif"; await tick();
  assert.match(trigger.textContent, /New Serif/);
  native.disabled = true; await tick();
  assert.ok(trigger.disabled);
  native.disabled = false; await tick();
  let inputs = 0, changes = 0;
  native.addEventListener("input", () => inputs++); native.addEventListener("change", () => changes++);
  trigger.dispatchEvent(new KeyboardEvent("keydown", { key: " ", bubbles: true })); await tick();
  const options = [...document.querySelectorAll('[role="option"]')];
  assert.equal(options.length, 3);
  options[0].click(); await tick();
  assert.equal(native.value, "");
  assert.equal(inputs, 1); assert.equal(changes, 1);
  const wrapper = native.parentElement;
  wrapper.remove(); await tick();
  document.querySelector('.kefe-panel').append(native); await tick();
  assert.equal(native.nextElementSibling?.getAttribute("data-slot"), "select-trigger");
  const dynamic = document.createElement("select");
  dynamic.setAttribute("aria-label", "Dynamic choice");
  dynamic.innerHTML = '<option value="one">One</option><option value="two">Two</option>';
  document.querySelector('.kefe-panel').append(dynamic); await tick();
  assert.equal(dynamic.nextElementSibling.getAttribute("data-slot"), "select-trigger", "dynamically added panel select is mounted");
  dynamic.hidden = true; await tick();
  assert.equal(dynamic.parentElement.hidden, true, "hiding the backing select hides its trigger");
  dynamic.hidden = false; await tick();
  assert.equal(dynamic.parentElement.hidden, false);
  const backing = document.createElement("select"); backing.id = "visualiserBackground";
  document.querySelector('.kefe-panel').append(backing); await tick();
  assert.equal(backing.parentElement.className, 'kefe-panel', "background mode's separate choice UI keeps its backing select unwrapped");
  const multi = document.createElement("select"); multi.multiple = true;
  document.querySelector('.kefe-panel').append(multi); await tick();
  assert.equal(multi.parentElement.className, 'kefe-panel', "multiple select is not converted to a single select");
  console.log("PASS: shadcn select bridge preserves empty values, dynamic options, hidden and disabled state, events and remounts");
} finally { await server.close(); dom.window.close(); }
